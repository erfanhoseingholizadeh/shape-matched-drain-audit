# Writes the training configs of the further-seed and near-margin runs and their one-epoch smoke twins.
# Run: python3 training/make_further_run_configs.py

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from pathlib import Path

import yaml

from slurm import cxr_settings

ROOT = Path(__file__).resolve().parent.parent
B = cxr_settings.get("cluster_root")
LABELS = ["Atelectasis", "Cardiomegaly", "Consolidation", "Edema", "Effusion", "Emphysema", "Fibrosis", "Pneumothorax", "Mass", "Nodule", "Pleural_Thickening", "Pneumonia", "Hernia", "Infiltration"]

def cfg(backbone: str, manifest: str, resolved: bool, out: str, epochs: int) -> dict:
    d = {"seed": 0, "backbone": backbone, "pretrained": True,
         "data": {"nih_root": f"{B}/data/raw/nih_chestxray14/images", "manifest_path": manifest, "image_size": 224},
         "train": {"epochs": epochs, "batch_size": 128, "lr": 0.0004, "lr_step_size": 5, "lr_gamma": 0.5, "num_workers": 16, "label_columns": LABELS, "class_weighting": True, "checkpoint_selection": True},
         "output_dir": out, "final_checkpoint_archive_dir": f"{B}/further_runs/checkpoints_archive"}
    if resolved:
        d["data"]["image_path_column"] = "resolved_path"
    return d

def main() -> None:
    jobs = []
    for arch in ("densenet121", "resnet50"):
        settings = ["e3lo", "e3hi"] + (["weak"] if arch == "resnet50" else [])
        for st in settings:
            jobs.append((f"e3_{arch}_{st}", cfg(arch, f"{B}/planted_control/outputs/resolved_manifest_{st}.csv", True, f"{B}/further_runs/outputs/e3_{arch}_{st}", 20)))
        jobs.append((f"e4_{arch}", cfg(arch, f"{B}/original_checkpoints/data/nih_pneumothorax_multilabel.csv", False, f"{B}/further_runs/outputs/e4_{arch}", 20)))
    for name, c in list(jobs):
        smoke = yaml.safe_load(yaml.safe_dump(c)); smoke["train"]["epochs"] = 1; smoke["output_dir"] += "_smoke"
        jobs.append((name + "_smoke", smoke))
    for name, c in jobs:
        p = ROOT / "configs" / f"{name}.yaml"
        p.write_text(f"# Generated by training/make_further_run_configs.py: recipe of the original and planted checkpoints for the E3 and E4 runs.\n" + yaml.safe_dump(c, sort_keys=False, width=200))
        print("wrote", p.name)

if __name__ == "__main__":
    main()
