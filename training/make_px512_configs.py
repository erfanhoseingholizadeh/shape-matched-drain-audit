# Writes the 512-pixel training configs and their smoke twins from the 224-pixel recipe and the recorded micro-batch sizes.
# Run: python3 training/make_px512_configs.py

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))


import json
from pathlib import Path

import yaml

from slurm import cxr_settings

ROOT = Path(__file__).resolve().parent.parent
B = cxr_settings.get("cluster_root")
LABELS = ["Atelectasis", "Cardiomegaly", "Consolidation", "Edema", "Effusion", "Emphysema", "Fibrosis", "Pneumothorax", "Mass", "Nodule", "Pleural_Thickening", "Pneumonia", "Hernia", "Infiltration"]
SMOKE_STEPS = 30
FAMILIES = {"orig": (f"{B}/original_checkpoints/data/nih_pneumothorax_multilabel.csv", False),
            "zero": (f"{B}/planted_control/outputs/resolved_manifest_zero.csv", True),
            "strong": (f"{B}/planted_control/outputs/resolved_manifest_strong.csv", True)}

def cfg(backbone: str, family: str, micro_batch: int, out: str, epochs: int, image_size: int = 512, tree: str = "replication_512") -> dict:
    manifest, resolved = FAMILIES[family]
    d = {"seed": 0, "backbone": backbone, "pretrained": True,
         "data": {"nih_root": f"{B}/data/raw/nih_chestxray14/images", "manifest_path": manifest, "image_size": image_size},
         "train": {"epochs": epochs, "batch_size": 128, "micro_batch": micro_batch, "lr": 0.0004, "lr_step_size": 5, "lr_gamma": 0.5, "num_workers": 16, "label_columns": LABELS,
                   "class_weighting": True, "checkpoint_selection": True},
         "output_dir": out, "final_checkpoint_archive_dir": f"{B}/{tree}/checkpoints_archive"}
    if resolved:
        d["data"]["image_path_column"] = "resolved_path"
    return d

def build(record: dict) -> dict[str, dict]:
    out: dict[str, dict] = {}
    for arch, short in (("densenet121", "dn"), ("resnet50", "rn")):
        m = int(record[arch])
        if 128 % m or m <= 0:
            raise ValueError(f"micro-batch {m} for {arch} does not divide 128")
        for fam in FAMILIES:
            name = f"e5_{arch}_{fam}"
            out[name] = cfg(arch, fam, m, f"{B}/replication_512/outputs/{name}", 20)
            smoke = yaml.safe_load(yaml.safe_dump(out[name]))
            smoke["train"]["epochs"] = 1
            smoke["train"]["max_batches_per_epoch"] = SMOKE_STEPS
            smoke["output_dir"] += "_smoke"
            out[name + "_smoke"] = smoke

        name = f"e5ctl224_{arch}"
        out[name] = cfg(arch, "orig", m, f"{B}/replication_512_ctl224/outputs/{name}", 20, image_size=224, tree="replication_512_ctl224")
        smoke = yaml.safe_load(yaml.safe_dump(out[name]))
        smoke["train"]["epochs"] = 1
        smoke["train"]["max_batches_per_epoch"] = SMOKE_STEPS
        smoke["output_dir"] += "_smoke"
        out[name + "_smoke"] = smoke
    return out

def header(name: str) -> str:
    if name.startswith("e5ctl224_"):
        return ("# Generated by training/make_px512_configs.py: the E4 224 recipe with micro_batch from configs/e5_microbatch.json, the E5 addendum "
                "(the 224-pixel micro-batch control).\n")
    return ("# Generated by training/make_px512_configs.py: the 224 recipe at 512 pixels; micro_batch from configs/e5_microbatch.json; "
            "for the E5 runs.\n")

def main() -> None:
    rec_path = ROOT / "configs" / "e5_microbatch.json"
    if not rec_path.exists():
        raise SystemExit("configs/e5_microbatch.json is missing: record the probe's measured micro-batches first (training/record_px512_microbatch.py)")
    record = json.loads(rec_path.read_text())
    for name, c in build(record).items():
        p = ROOT / "configs" / f"{name}.yaml"
        p.write_text(header(name)
                     + yaml.safe_dump(c, sort_keys=False, width=200))
        print("wrote", p.name)

if __name__ == "__main__":
    main()
